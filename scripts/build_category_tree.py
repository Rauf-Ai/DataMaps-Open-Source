def classify(name: str) -> tuple[str, str]:
    n = name.lower()
    for pattern, top, sub in RULES:
        try:
            if re.search(pattern, n, flags=re.IGNORECASE | re.UNICODE):
                return top, sub
        except re.error:
            continue
    return "Прочее", "Без категории"


def build_tree(categories: list[str]) -> list[dict]:
    """Возвращает упорядоченный список разделов с подкатегориями."""
    tree: dict[str, dict[str, list[str]]] = {}
    for c in categories:
        top, sub = classify(c)
        tree.setdefault(top, {}).setdefault(sub, []).append(c)
    out: list[dict] = []
    for top in sorted(tree.keys(), key=lambda x: (x == "Прочее", x)):
        subs = tree[top]
        sub_list = []
        for sub in sorted(subs.keys()):
            cats = sorted(subs[sub])
            sub_list.append({"name": sub, "count": len(cats), "categories": cats})
        out.append({"name": top, "subcategories": sub_list, "count": sum(len(s["categories"]) for s in sub_list)})
    return out


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--csv-dir", default=None)
    p.add_argument("--from-txt", default=None, help="прочитать категории из txt-файла (по одной на строку)")
    p.add_argument("--out", default="/data/category_tree.json")
    args = p.parse_args()

    if args.from_txt:
        cats = [line.strip() for line in Path(args.from_txt).read_text(encoding="utf-8").splitlines() if line.strip()]
    elif args.csv_dir:
        cats = sorted(f.stem for f in Path(args.csv_dir).glob("*.csv"))
    else:
        print("Укажите --csv-dir или --from-txt", file=sys.stderr)
        return 1

    tree = build_tree(cats)
    Path(args.out).write_text(json.dumps(tree, ensure_ascii=False, indent=2), encoding="utf-8")

    total = sum(t["count"] for t in tree)
    other = next((t["count"] for t in tree if t["name"] == "Прочее"), 0)
    print(f"Категорий: {total}, в «Прочем»: {other} ({other*100//max(total,1)}%)")
    for t in tree:
        print(f"  {t['name']}: {t['count']}")
    print(f"\nДерево сохранено: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
